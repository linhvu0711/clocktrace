import XCTest

@testable import HelperCore

final class SegbTests: XCTestCase {
  func testReturnsNotSegbWithoutTheMagic() {
    // Given: a 40-byte buffer starting with "SEGA"
    let data = Data([0x53, 0x45, 0x47, 0x41] + [UInt8](repeating: 0, count: 36))
    // When
    let read = readSegb(data)
    // Then
    XCTAssertEqual(read, .notSegb)
  }

  func testReturnsNotSegbForAShortFile() {
    // Given: only the magic, no header
    let data = Data("SEGB".utf8)
    // When
    let read = readSegb(data)
    // Then
    XCTAssertEqual(read, .notSegb)
  }

  func testReturnsNotSegbWhenTheTrailerDoesNotFit() {
    // Given: count 5 but only 16 trailer bytes
    let data = Data(
      [
        0x53, 0x45, 0x47, 0x42, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x7f, 0xed, 0x3e,
        0xc7, 0x41,
      ] + [UInt8](repeating: 0, count: 16))
    // When
    let read = readSegb(data)
    // Then
    XCTAssertEqual(read, .notSegb)
  }

  func testReturnsNoEntriesForAnEmptyFile() {
    // Given: count 0
    let data = Data(
      [
        0x53, 0x45, 0x47, 0x42, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x7f, 0xed, 0x3e,
        0xc7, 0x41,
      ] + [UInt8](repeating: 0, count: 16))
    // When
    let read = readSegb(data)
    // Then
    XCTAssertEqual(read, .entries([]))
  }

  func testReadsWrittenEntriesInOffsetOrder() {
    // Given: two written entries, the trailer listed in reverse order
    let data = Data([
      0x53, 0x45, 0x47, 0x42, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x7f, 0xed, 0x3e,
      0xc7, 0x41, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x1d, 0x80, 0xbc, 0x55, 0x0a, 0x00, 0x00, 0x00, 0x01, 0x02,
      0x03, 0x00, 0x74, 0x23, 0xdf, 0x55, 0x0a, 0x00, 0x00, 0x00, 0x04, 0x05, 0x00, 0x00,
      0x16, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0xed, 0x3e,
      0xc7, 0x41, 0x0b, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80,
      0xed, 0x3e, 0xc7, 0x41,
    ])
    // When
    let read = readSegb(data)
    // Then
    XCTAssertEqual(
      read,
      .entries([
        SegbEntry(offset: 32, payload: Data([1, 2, 3])),
        SegbEntry(offset: 44, payload: Data([4, 5])),
      ]))
  }

  func testSkipsDeletedEmptyAndZeroSlots() {
    // Given: written, deleted, written, plus a state-4 slot and a zeroed slot
    let data = Data([
      0x53, 0x45, 0x47, 0x42, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x7f, 0xed, 0x3e,
      0xc7, 0x41, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x1d, 0x80, 0xbc, 0x55, 0x0a, 0x00, 0x00, 0x00, 0x01, 0x02,
      0x03, 0x00, 0x84, 0xe2, 0xf5, 0x11, 0x0a, 0x00, 0x00, 0x00, 0x09, 0x09, 0x09, 0x09,
      0x09, 0x00, 0x00, 0x00, 0x9b, 0x11, 0xfc, 0x90, 0x0a, 0x00, 0x00, 0x00, 0x07, 0x07,
      0x00, 0x00, 0x0b, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80,
      0xed, 0x3e, 0xc7, 0x41, 0x19, 0x00, 0x00, 0x00, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x80, 0x80, 0xed, 0x3e, 0xc7, 0x41, 0x26, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x81, 0xed, 0x3e, 0xc7, 0x41, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ])
    // When
    let read = readSegb(data)
    // Then
    XCTAssertEqual(
      read,
      .entries([
        SegbEntry(offset: 32, payload: Data([1, 2, 3])),
        SegbEntry(offset: 60, payload: Data([7, 7])),
      ]))
  }
}
